#!/usr/bin/env python3
"""Write /etc/go2rtc.yaml from the Nest secrets in ~/.config/homelab."""
from __future__ import annotations

import json
import os
import urllib.parse
import urllib.request
from pathlib import Path

CONF = Path.home() / ".config" / "homelab"
OUT = Path(os.environ.get("GO2RTC_CONFIG", "/etc/go2rtc.yaml"))


def read(name: str) -> str:
    return (CONF / name).read_text().strip()


def device_id() -> str:
    path = CONF / "nest-device-id"
    if path.exists() and path.read_text().strip():
        return path.read_text().strip()

    tok = json.load(urllib.request.urlopen("https://oauth2.googleapis.com/token", urllib.parse.urlencode({
        "client_id": read("google-client-id"),
        "client_secret": read("google-client-secret"),
        "refresh_token": read("google-refresh-token"),
        "grant_type": "refresh_token",
    }).encode()))
    url = (
        f"https://smartdevicemanagement.googleapis.com/v1/enterprises/"
        f"{read('sdm-project-id')}/devices"
    )
    req = urllib.request.Request(url, headers={"Authorization": "Bearer " + tok["access_token"]})
    devices = json.load(urllib.request.urlopen(req))["devices"]
    doorbells = [d for d in devices if d["type"].endswith("DOORBELL")]
    if not doorbells:
        raise SystemExit("no Nest doorbell found in Device Access")
    device = doorbells[0]["name"].rsplit("/", 1)[-1]
    path.write_text(device + "\n")
    os.chmod(path, 0o600)
    return device


def main() -> None:
    query = urllib.parse.urlencode({
        "client_id": read("google-client-id"),
        "client_secret": read("google-client-secret"),
        "refresh_token": read("google-refresh-token"),
        "project_id": read("sdm-project-id"),
        "device_id": device_id(),
    })
    # Bind only to localhost. Secrets live in this file; keep permissions 600.
    text = f"""# Generated by write_go2rtc_config.py. Do not edit by hand.
api:
  listen: "127.0.0.1:1984"
rtsp:
  listen: "127.0.0.1:8554"
webrtc:
  listen: "127.0.0.1:8555"
  candidates: []
streams:
  doorbell: "nest:?{query}"
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    os.chmod(OUT, 0o600)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
